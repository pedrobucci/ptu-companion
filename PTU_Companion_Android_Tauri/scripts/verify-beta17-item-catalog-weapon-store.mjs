import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const app=fs.readFileSync(path.join(root,'www/app.js'),'utf8');
const api=fs.readFileSync(path.join(root,'www/mobile-api.mjs'),'utf8');
const runtime=fs.readFileSync(path.join(root,'www/mobile-runtime.js'),'utf8');
const mobile=JSON.parse(fs.readFileSync(path.join(root,'www/mobile-data.json'),'utf8'));
assert.equal(Object.keys(mobile.resolved?.['all-provided-material']?.items||{}).length,508);
assert(mobile.packs.some(p=>p.id==='campaign-homebrew-custom-weapons'&&p.version==='2.1.0'&&!p.androidImported));
assert(mobile.rulesets.find(r=>r.id==='all-provided-material')?.packs.some(p=>p.pack_id==='campaign-homebrew-custom-weapons'&&p.enabled));
assert(app.includes("setShopPreset('Weapon Store',0)"));
assert(app.includes("shops.includes('Weapon Store')"));
assert(app.includes('ensureInventoryItemForPurchase'));
assert(app.includes('async function loadItemCatalog(force=false)'));
assert(api.includes('shopCategories:Array.isArray(raw.shop_categories)'));
assert(runtime.includes('shopCategories:Array.isArray(raw.shop_categories)'));
assert(runtime.includes("version:'2.2.0-android-beta.22'"));
const pack=fs.readFileSync(path.join(root,'Content Packs/campaign-homebrew-custom-weapons-2.1.0.ptucp'));
assert(pack.length>1000);
console.log('PTU Companion Android v2.2.0-beta.22 item catalog + Weapon Store verification: OK');
