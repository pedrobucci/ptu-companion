import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const repo=resolve(fileURLToPath(new URL('../../',import.meta.url)));
const sourcePath=resolve(repo,'docs/data/PTU_FORMS_STAGE_B.json');
const outputPaths=[
  resolve(repo,'PTU_Companion_Android_Tauri/www/rules/mega-form-runtime-data.mjs'),
  resolve(repo,'PTU_Companion_Windows_Source/rules/mega-form-runtime-data.mjs')
];
const source=JSON.parse(await readFile(sourcePath,'utf8'));
const rows=source.synthetic_transform_species.filter(row=>row.source_family==='mega-evolution');
assert.equal(rows.reduce((sum,row)=>sum+row.forms.length,0),48,'Expected all 48 source-catalog Mega Forms');

const formsBySpecies={};
const items=[];
for(const row of rows){
  assert.equal(row.forms.length,row.source_effects.length,`${row.species_id} form/effect source rows must align`);
  formsBySpecies[row.species_id]=row.forms.map((sourceForm,index)=>{
    const form=structuredClone(sourceForm);
    const effect=row.source_effects[index];
    const suffix=form.id==='mega'?'':`-${form.id}`;
    const itemId=row.species_id==='sableye'&&form.id==='mega'?'sableye-mega-stone':`mega-stone-${row.species_id}${suffix}`;
    const variant=form.id==='mega'?'':` ${form.id.replace(/^mega-/,'').toUpperCase()}`;
    const itemName=`${row.species_id.replace(/(^|-)([a-z])/g,(_,sep,char)=>`${sep==='-'?' ':''}${char.toUpperCase()}`)} Mega Stone${variant}`;
    const all=Array.isArray(form.requirements?.all)?form.requirements.all:[];
    const megaRingGate=all.map(requirement=>requirement.kind==='manual'&&typeof requirement.value==='string'
      ?{...requirement,value:{id:requirement.value,label:'Trainer has the Mega Ring'}}:requirement);
    form.requirements={all:[{kind:'held_item',value:itemId},...megaRingGate]};
    form.grantedAbilities=effect.ability_added?[effect.ability_added]:[];
    form.source={packName:'Gen 8ish PokéDex',page:effect.source_page};
    form.appItemId=itemId;
    const artworkSuffix=form.id==='mega'?'':`-${form.id.replace(/^mega-/,'')}`;
    form.overrides={...(form.overrides||{}),artwork:{replace:`creatures/forms/mega-${row.species_id}${artworkSuffix}.png`}};
    items.push({
      id:itemId,name:itemName,speciesId:row.species_id,formId:form.id,
      effect:`App helper label for the species/form-specific Mega Stone described by PTU Core 1.05 p.206. The supplied source does not define this item's official display name or price.`,
      sourcePage:206
    });
    return form;
  });
}
assert.equal(items.length,48,'Each Mega Form must have one species/form-specific helper Stone');
assert.equal(new Set(items.map(item=>item.id)).size,48,'Mega Stone helper IDs must be unique');
const generated=`// Generated by scripts/generate-mega-form-runtime.mjs from docs/data/PTU_FORMS_STAGE_B.json.\nexport const MEGA_FORM_CATALOG=${JSON.stringify(formsBySpecies,null,2)};\nexport const MEGA_STONE_CATALOG=${JSON.stringify(items,null,2)};\n`;
for(const path of outputPaths)await writeFile(path,generated,'utf8');
console.log(`Generated ${Object.keys(formsBySpecies).length} species, ${items.length} Mega Forms and helper Stone labels.`);
